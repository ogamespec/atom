"""Шахматная доска Фейнмана / квантовая прогулка Дирака (1+1D) — локальное правило материи.

Правило (один такт CLK, шаг ε по времени и по пространству, c = 1):
  1) МОНЕТА (локально, в каждой ячейке): поворот двухкомпонентного спинора
        [ψR']   [ cos θ   −i·sin θ ] [ψR]
        [ψL'] = [ −i·sin θ   cos θ ] [ψL],      θ = m·ε;
  2) СДВИГ (локально): ψR(x) ← ψR'(x−ε),  ψL(x) ← ψL'(x+ε)   (R вправо, L влево).

Континуальный предел ε→0: (∂_t + ∂_x)ψR = −im ψL,  (∂_t − ∂_x)ψL = −im ψR —
уравнение Дирака (1+1D) с массой m. Дисперсия ω = √(m² + k²); при k ≪ m:
ω ≈ m + k²/(2m) — нерелятивистский предел Шрёдингера (m — энергия покоя).
Спин-½ — это двухкомпонентность, возникающая из двухшаговой структуры правила
(монета + сдвиг): «спин» не постулируется, а следует из правила движения.

Свойства: правило унитарно (норма сохраняется), локально (2 соседа),
информация распространяется со скоростью ≤ 1 ячейки/такт = c.
"""
import numpy as np


def step(psiR, psiL, eps, m):
    """Один такт КА. Возвращает (ψR, ψL) на следующем слое времени (тор)."""
    c, s = np.cos(m * eps), np.sin(m * eps)
    newR = c * psiR - 1j * s * psiL
    newL = c * psiL - 1j * s * psiR
    return np.roll(newR, 1), np.roll(newL, -1)


def dispersion(eps, m, k):
    """Точная дисперсия правила: ω(k) = arg λ(k)/ε (положительная ветвь)."""
    c = np.cos(m * eps)
    k = np.asarray(k, dtype=float)
    cc = c * np.cos(k * eps)
    lam = cc + 1j * np.sqrt(np.maximum(1.0 - cc ** 2, 0.0))
    return np.angle(lam) / eps


def norm(psiR, psiL):
    """Σ(|ψR|² + |ψL|²)."""
    return float(np.sum(np.abs(psiR) ** 2) + np.sum(np.abs(psiL) ** 2))


def mean_x(psiR, psiL, eps):
    """⟨x⟩ по полной плотности вероятности."""
    x = eps * np.arange(len(psiR))
    p = np.abs(psiR) ** 2 + np.abs(psiL) ** 2
    return float(np.sum(x * p) / np.sum(p))
