"""Физические константы (CODATA 2018) и атомные единицы.

Атомные единицы (а.е.): hbar = m_e = e = 4*pi*eps0 = 1.
Тогда боровский радиус a0 = 1, энергия измеряется в хартри
(1 хартри = 27.211386 эВ), время — в единицах hbar/E_h = 2.419e-17 с,
скорость света c = 1/alpha = 137.036 а.е.
"""

M_E_KG = 9.1093837015e-31        # масса электрона, кг
M_P_KG = 1.67262192369e-27       # масса протона, кг
M_P_OVER_M_E = M_P_KG / M_E_KG   # 1836.152673...

HBAR_JS = 1.054571817e-34        # Дж*с
E_CHARGE = 1.602176634e-19       # Кл
C_LIGHT = 2.99792458e8           # м/с
EPS0 = 8.8541878128e-12          # Ф/м
A0_M = 5.29177210903e-11         # боровский радиус, м
E_HARTREE_J = 4.3597447222071e-18
EV_J = 1.602176634e-19
E_HARTREE_EV = E_HARTREE_J / EV_J      # 27.211386245988 эВ
RYDBERG_EV = 13.605693122994           # энергия Ридберга, эВ
RYDBERG_M1 = 10973731.568160            # постоянная Ридберга (бесконечная масса ядра), 1/м
R_H_M1 = RYDBERG_M1 / (1.0 + 1.0 / M_P_OVER_M_E)  # для протона: 10967758 м⁻¹
ALPHA = 7.2973525693e-3                # постоянная тонкой структуры
C_AU = 1.0 / ALPHA                     # скорость света, а.е.
T_AU_S = HBAR_JS / E_HARTREE_J         # единица времени, с


def ev_to_au(e):
    return e / E_HARTREE_EV


def au_to_ev(e):
    return e * E_HARTREE_EV


def wavelength_nm(n1, n2):
    """Длина волны перехода n2 -> n1, нм (формула Ридберга, конечная масса ядра)."""
    return 1e9 / (R_H_M1 * (1.0 / n1 ** 2 - 1.0 / n2 ** 2))
